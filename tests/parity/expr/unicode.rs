//! Regenerate the expression lexer's character tables with the pinned Rust toolchain.
fn table(name: &str, predicate: fn(char) -> bool) {
    println!("{name}: tuple[int, ...] = (");
    let mut previous = false;
    for scalar in 0..=0x110000 {
        let member = char::from_u32(scalar).is_some_and(predicate);
        if member != previous {
            println!("    {scalar},");
        }
        previous = member;
    }
    println!(")\n");
}

fn main() {
    println!("\"\"\"Generated by tests/parity/expr/unicode.rs using Rust 1.96.0; do not edit.\"\"\"\n");
    println!("UNICODE_VERSION = {:?}\n", char::UNICODE_VERSION);
    table("ALPHABETIC", char::is_alphabetic);
    table("ALPHANUMERIC", char::is_alphanumeric);
    table("WHITESPACE", char::is_whitespace);
}
